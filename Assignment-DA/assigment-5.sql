SELECT category, SUM(units_sold) AS total_units_sold FROM sales GROUP BY category HAVING SUM(units_sold)>20;
SELECT REGION, SUM(units_sold*unit_price) AS total_revenue FROM sales GROUP BY region HAVING SUM(units_sold*unit_price)>50000;
SELECT category, COUNT(*) AS total_products FROM sales GROUP BY category HAVING COUNT(*)>2;
