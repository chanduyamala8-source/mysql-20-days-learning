-- List all students with the courses they are enrolled in.
SELECT S.NAME, C.COURSE_NAME FROM STUDENTS S INNER JOIN ENROLLMENTS E ON S.STUDENT_ID = E.STUDENT_ID INNER JOIN COURSES C ON E.COURSE_ID = C.COURSE_ID;

-- Show course names along with student names.
SELECT C.COURSE_NAME,S.NAME AS STUDENT_NAME FROM COURSES C JOIN ENROLLMENTS E ON C.COURSE_ID=E.COURSE_ID JOIN STUDENTS S ON E.STUDENT_ID=S.STUDENT_ID;

-- Get names of students enrolled in "Physics".
SELECT S.NAME FROM STUDENTS S JOIN ENROLLMENTS E ON S.STUDENT_ID=E.STUDENT_ID JOIN COURSES C ON E.COURSE_ID=C.COURSE_ID WHERE C.COURSE_NAME='PHYSICS';

-- List all students with their courses, if enrolled.
SELECT S.NAME AS STUDENT_NAME, C.COURSE_NAME FROM STUDENTS S LEFT JOIN ENROLLMENTS E ON S.STUDENT_ID = E.STUDENT_ID LEFT JOIN COURSES C ON E.COURSE_ID = C.COURSE_ID;

-- Show all courses and the students who enrolled, even if none.
SELECT C.COURSE_NAME, S.NAME AS STUDENT_NAME FROM COURSES C LEFT JOIN ENROLLMENTS E ON C.COURSE_ID = E.COURSE_ID LEFT JOIN STUDENTS S ON E.STUDENT_ID = S.STUDENT_ID;

-- Display all students with course details, even if some courses have no enrollments.
SELECT S.NAME, C.COURSE_NAME FROM STUDENTS S LEFT JOIN ENROLLMENTS E ON S.STUDENT_ID = E.STUDENT_ID LEFT JOIN COURSES C ON E.COURSE_ID = C.COURSE_ID;

-- List all students and all courses, even if there is no match (simulate FULL JOIN).
SELECT S.NAME, C.COURSE_NAME FROM STUDENTS S LEFT JOIN ENROLLMENTS E ON S.STUDENT_ID = E.STUDENT_ID LEFT JOIN COURSES C
ON E.COURSE_ID = C.COURSE_ID
UNION
SELECT S.NAME, C.COURSE_NAME FROM COURSES C LEFT JOIN ENROLLMENTS E ON C.COURSE_ID = E.COURSE_ID LEFT JOIN STUDENTS S
ON E.STUDENT_ID = S.STUDENT_ID;

-- Show pairs of students who have the same age.
SELECT S1.NAME AS STUDENT1, S2.NAME AS STUDENT2, S1.AGE FROM STUDENTS S1 JOIN STUDENTS S2 ON S1.AGE = S2.AGE
AND S1.STUDENT_ID < S2.STUDENT_ID;

-- Count how many students are enrolled in each course.
SELECT C.COURSE_NAME, COUNT(E.STUDENT_ID) AS TOTAL_STUDENTS
FROM COURSES C
LEFT JOIN ENROLLMENTS E
ON C.COURSE_ID = E.COURSE_ID
GROUP BY C.COURSE_ID, C.COURSE_NAME;

-- Show the number of courses each student is enrolled in.
SELECT S.NAME, COUNT(E.COURSE_ID) AS TOTAL_COURSES
FROM STUDENTS S
LEFT JOIN ENROLLMENTS E
ON S.STUDENT_ID = E.STUDENT_ID
GROUP BY S.STUDENT_ID, S.NAME;

-- List all students and their courses ordered by student name.
SELECT S.NAME, C.COURSE_NAME
FROM STUDENTS S
LEFT JOIN ENROLLMENTS E
ON S.STUDENT_ID = E.STUDENT_ID
LEFT JOIN COURSES C
ON E.COURSE_ID = C.COURSE_ID
ORDER BY S.NAME ASC;

-- Show student names and course names ordered by course name.
SELECT S.NAME, C.COURSE_NAME
FROM STUDENTS S
INNER JOIN ENROLLMENTS E
ON S.STUDENT_ID = E.STUDENT_ID
INNER JOIN COURSES C
ON E.COURSE_ID = C.COURSE_ID
ORDER BY C.COURSE_NAME ASC;

-- Show only courses with more than one student enrolled.
SELECT C.COURSE_NAME, COUNT(E.STUDENT_ID) AS TOTAL_STUDENTS
FROM COURSES C
INNER JOIN ENROLLMENTS E
ON C.COURSE_ID = E.COURSE_ID
GROUP BY C.COURSE_ID, C.COURSE_NAME
HAVING COUNT(E.STUDENT_ID) > 1;

-- List students enrolled in more than one course.
SELECT S.NAME, COUNT(E.COURSE_ID) AS TOTAL_COURSES
FROM STUDENTS S
INNER JOIN ENROLLMENTS E
ON S.STUDENT_ID = E.STUDENT_ID
GROUP BY S.STUDENT_ID, S.NAME
HAVING COUNT(E.COURSE_ID) > 1;

-- Display student names and count of enrollments, ordered
SELECT S.NAME, COUNT(E.ENROLLMENT_ID) AS TOTAL_ENROLLMENTS
FROM STUDENTS S
LEFT JOIN ENROLLMENTS E
ON S.STUDENT_ID = E.STUDENT_ID
GROUP BY S.STUDENT_ID, S.NAME
ORDER BY TOTAL_ENROLLMENTS DESC;